using System.Text;
using Microsoft.AspNetCore.Http;
using StudentSupport.Models;

namespace StudentSupport.Services;

/// <summary>Small classroom upload store, outside webroot; not a substitute for malware scanning in production.</summary>
public class AttachmentService(IWebHostEnvironment env)
{
    public const long MaxBytes = 5 * 1024 * 1024;
    private static readonly Dictionary<string, string> Types = new(StringComparer.OrdinalIgnoreCase)
    {
        [".pdf"] = "application/pdf", [".png"] = "image/png", [".jpg"] = "image/jpeg",
        [".jpeg"] = "image/jpeg", [".txt"] = "text/plain"
    };
    private string Root => Path.Combine(env.ContentRootPath, "App_Data", "attachments");

    public string Resolve(string storedName)
    {
        // Storage names are always generated by this service; validate again before reading.
        if (storedName.Length < 33 || storedName.Length > 40 ||
            !System.Text.RegularExpressions.Regex.IsMatch(storedName, @"\A[a-f0-9]{32}\.(pdf|png|jpg|jpeg|txt)\z"))
            throw new InvalidOperationException("Tên tệp lưu trữ không hợp lệ.");
        return Path.Combine(Root, storedName);
    }

    public async Task<TicketAttachment> SaveAsync(IFormFile file, int ticketId, int authorId)
    {
        if (file.Length == 0 || file.Length > MaxBytes) throw new ArgumentException("Kích thước tệp phải từ 1 B đến 5 MB.");
        var sourceName = file.FileName.Replace('\\', '/');
        var safeName = Path.GetFileName(sourceName);
        if (string.IsNullOrWhiteSpace(safeName) || safeName.Length > 180 || safeName.Any(char.IsControl))
            throw new ArgumentException("Tên tệp không hợp lệ.");
        var extension = Path.GetExtension(safeName).ToLowerInvariant();
        if (!Types.TryGetValue(extension, out var mime))
            throw new ArgumentException("Chỉ nhận PDF, PNG, JPG/JPEG hoặc TXT.");
        Directory.CreateDirectory(Root);
        var storedName = Guid.NewGuid().ToString("N") + extension;
        var path = Resolve(storedName);
        try
        {
            await using (var output = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None))
            {
                await file.CopyToAsync(output);
                if (output.Length == 0 || output.Length > MaxBytes) throw new ArgumentException("Tệp vượt giới hạn cho phép.");
            }
            var bytes = await File.ReadAllBytesAsync(path);
            var valid = extension switch
            {
                ".pdf" => bytes.Length >= 5 && bytes.AsSpan(0, 5).SequenceEqual("%PDF-"u8),
                ".png" => bytes.Length >= 8 && bytes.AsSpan(0, 8).SequenceEqual(new byte[] {137,80,78,71,13,10,26,10}),
                ".jpg" or ".jpeg" => bytes.Length >= 4 && bytes[0] == 255 && bytes[1] == 216 && bytes[^2] == 255 && bytes[^1] == 217,
                ".txt" => ValidateText(bytes),
                _ => false
            };
            if (!valid) throw new ArgumentException("Nội dung tệp không khớp định dạng.");
            return new TicketAttachment { TicketId = ticketId, UploadedById = authorId,
                OriginalName = safeName, StoredName = storedName, ContentType = mime, FileSize = bytes.Length };
        }
        catch { if (File.Exists(path)) File.Delete(path); throw; }
    }

    private static bool ValidateText(byte[] bytes)
    {
        if (bytes.Contains((byte)0)) return false;
        try { _ = new UTF8Encoding(false, true).GetString(bytes); return true; }
        catch (DecoderFallbackException) { return false; }
    }

    public void DeleteSaved(TicketAttachment file)
    {
        var path = Resolve(file.StoredName);
        if (File.Exists(path)) File.Delete(path);
    }
}
